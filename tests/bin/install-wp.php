<?php
/**
 * Builds the WordPress + WooCommerce site the integration tests run against, in
 * .wp-test/, on SQLite (no MySQL needed). Run through scripts/setup-test-wp.mjs.
 *
 * Usage: php tests/bin/install-wp.php <cache dir> <target dir> <wordpress.zip> <woocommerce.zip> <sqlite.zip>
 *
 * @package WooAIProductWriter
 */

if ( 'cli' !== PHP_SAPI ) {
	exit( 1 );
}

[ , $cache, $target, $wp_zip, $wc_zip, $sqlite_zip ] = $argv + array_fill( 0, 6, '' );
$repo = dirname( __DIR__, 2 );

function wapw_extract( string $zip_file, string $to, string $strip_prefix = '' ): void {
	$zip = new ZipArchive();
	if ( true !== $zip->open( $zip_file ) ) {
		fwrite( STDERR, "Can't open $zip_file\n" );
		exit( 1 );
	}
	for ( $i = 0; $i < $zip->numFiles; $i++ ) {
		$name = $zip->getNameIndex( $i );
		$rel  = '' !== $strip_prefix && str_starts_with( $name, $strip_prefix ) ? substr( $name, strlen( $strip_prefix ) ) : $name;
		if ( '' === $rel ) {
			continue;
		}
		$path = $to . '/' . $rel;
		if ( str_ends_with( $name, '/' ) ) {
			is_dir( $path ) || mkdir( $path, 0777, true );
			continue;
		}
		is_dir( dirname( $path ) ) || mkdir( dirname( $path ), 0777, true );
		file_put_contents( $path, $zip->getFromIndex( $i ) );
	}
	$zip->close();
}

if ( ! file_exists( "$target/wp-settings.php" ) ) {
	echo "Extracting WordPress…\n";
	wapw_extract( "$cache/$wp_zip", $target, 'wordpress/' );
}
foreach ( array( $wc_zip => 'woocommerce', $sqlite_zip => 'sqlite-database-integration' ) as $zip => $slug ) {
	if ( ! is_dir( "$target/wp-content/plugins/$slug" ) ) {
		echo "Extracting $slug…\n";
		wapw_extract( "$cache/$zip", "$target/wp-content/plugins" );
	}
}

// SQLite drop-in.
$db_copy = file_get_contents( "$target/wp-content/plugins/sqlite-database-integration/db.copy" );
$db_copy = str_replace(
	array( "'{SQLITE_IMPLEMENTATION_FOLDER_PATH}'", "'{SQLITE_PLUGIN}'" ),
	array( "__DIR__ . '/plugins/sqlite-database-integration'", "'sqlite-database-integration/load.php'" ),
	$db_copy
);
file_put_contents( "$target/wp-content/db.php", $db_copy );

// Loads the plugin from the repo root, so tests always run the working copy.
is_dir( "$target/wp-content/mu-plugins" ) || mkdir( "$target/wp-content/mu-plugins", 0777, true );
file_put_contents(
	"$target/wp-content/mu-plugins/load-woo-ai-product-writer.php",
	"<?php\n// Generated by tests/bin/install-wp.php.\nadd_action( 'muplugins_loaded', static function () {\n\trequire_once dirname( __DIR__, 3 ) . '/woo-ai-product-writer.php';\n} );\n"
);

file_put_contents(
	"$target/wp-config.php",
	<<<'PHP'
<?php
// Generated by tests/bin/install-wp.php. Test site only.
define( 'DB_NAME', 'wordpress' );
define( 'DB_USER', '' );
define( 'DB_PASSWORD', '' );
define( 'DB_HOST', '' );
define( 'DB_CHARSET', 'utf8mb4' );
define( 'DB_COLLATE', '' );
define( 'DB_DIR', __DIR__ . '/wp-content/database/' );
define( 'DB_FILE', '.ht.sqlite' );
define( 'WP_HOME', 'http://example.test' );
define( 'WP_SITEURL', 'http://example.test' );
define( 'AUTH_KEY', 'test' );
define( 'SECURE_AUTH_KEY', 'test' );
define( 'LOGGED_IN_KEY', 'test' );
define( 'NONCE_KEY', 'test' );
define( 'AUTH_SALT', 'test' );
define( 'SECURE_AUTH_SALT', 'test' );
define( 'LOGGED_IN_SALT', 'test' );
define( 'NONCE_SALT', 'test' );
define( 'WP_DEBUG', true );
// The first load runs before WooCommerce has created its tables; setup hides that noise.
define( 'WP_DEBUG_DISPLAY', ! getenv( 'WAPW_QUIET' ) );
define( 'DISABLE_WP_CRON', true );
define( 'WP_HTTP_BLOCK_EXTERNAL', true );
define( 'AUTOMATIC_UPDATER_DISABLED', true );
define( 'WP_ENVIRONMENT_TYPE', 'local' );
$table_prefix = 'wp_';
if ( ! defined( 'ABSPATH' ) ) {
	define( 'ABSPATH', __DIR__ . '/' );
}
require_once ABSPATH . 'wp-settings.php';
PHP
);

if ( file_exists( "$target/wp-content/database/.ht.sqlite" ) ) {
	echo "Site already installed.\n";
	exit( 0 );
}

echo "Installing WordPress…\n";
define( 'WP_INSTALLING', true );
$_SERVER['HTTP_HOST']   = 'example.test';
$_SERVER['SERVER_NAME'] = 'example.test';
$_SERVER['REQUEST_URI'] = '/';
require "$target/wp-load.php";
require_once ABSPATH . 'wp-admin/includes/upgrade.php';
require_once ABSPATH . 'wp-admin/includes/plugin.php';

$result = wp_install( 'AI Product Writer tests', 'admin', 'admin@example.test', false, '', 'password' );
if ( is_wp_error( $result ) ) {
	fwrite( STDERR, $result->get_error_message() . "\n" );
	exit( 1 );
}
update_option( 'permalink_structure', '/%postname%/' );

// Activated through the option rather than activate_plugin(): WooCommerce creates its
// tables on the next normal load (WC_Install::check_version on init), which
// scripts/setup-test-wp.mjs triggers with tests/bin/warm-up.php.
update_option( 'active_plugins', array( 'woocommerce/woocommerce.php' ) );
echo "WordPress installed.\n";

function destroySession($data = null) {
    if ($data === null) return null;
    return $data;
}